using argus.Server.Imports;
using UglyToad.PdfPig;

namespace argus.Server.Tests;

public sealed class PdfEmptyUserAccessTests
{
    // Vectors generated with a separate Python 3 implementation using the
    // cryptography package for ISO 32000-2 Algorithm 2.B. The same Python
    // implementation reproduces the user hash in both approved private samples.
    [Theory]
    [InlineData("0000000000000000", "439feba099a63d0d035a1e5fb67ff307329189584956425aff2d3bd3d15edc60")]
    [InlineData("0001020304050607", "1403c04eb647d2e60452dfc4eb0a5e0cf322e8a83a759eabbd17d498a93ba041")]
    [InlineData("ffffffffffffffff", "47d51b9c3d77a95f476d54a54f8300c6a044dbb7c694f0ce515507f9e90ac9cb")]
    public void EmptyPasswordRevision6HashMatchesIndependentVectors(string saltHex, string expectedHex)
    {
        byte[] salt = Convert.FromHexString(saltHex);
        byte[] expected = Convert.FromHexString(expectedHex);

        byte[] actual = PdfEmptyUserAccess.ComputeR6Hash(ReadOnlySpan<byte>.Empty, salt, ReadOnlySpan<byte>.Empty);

        Assert.Equal(expected, actual);
    }

    [Fact]
    public void Revision6HashRejectsAShortOwnerVector()
    {
        Assert.Throws<ArgumentException>(() => PdfEmptyUserAccess.ComputeR6Hash(ReadOnlySpan<byte>.Empty, new byte[8], new byte[47]));
    }

    // Synthetic R6 fixtures generated by an independent Python 3 /
    // cryptography implementation of ISO 32000-2 Algorithm 2.B and AES-256.
    // The generator never calls the production guard and the files contain no
    // customer data.
    [Theory]
    [InlineData("synthetic-r6-empty-user.pdf", true)]
    [InlineData("synthetic-r6-nonempty-user-empty-owner.pdf", false)]
    [InlineData("synthetic-r6-corrupt-u-empty-owner.pdf", false)]
    [InlineData("synthetic-r6-corrupt-ue.pdf", false)]
    [InlineData("synthetic-r6-corrupt-perms.pdf", false)]
    [InlineData("synthetic-r6-wrong-revision.pdf", false)]
    public void SyntheticRevision6ProtectionControls(string name, bool expected)
    {
        string path = Path.Combine(AppContext.BaseDirectory, "Fixtures", "Statements", name);
        Assert.True(File.Exists(path), $"The synthetic fixture {name} is missing.");
        using PdfDocument document = PdfDocument.Open(File.ReadAllBytes(path));

        Assert.Equal(expected, PdfEmptyUserAccess.Verify(document));
    }

    // Two-key controls: the encryption dictionary's user fields are consistent
    // with one key while the owner fields and the content use another. Stripping
    // owner authentication must force the user key, so only the same-key file
    // yields the synthetic text.
    [Theory]
    [InlineData("synthetic-two-key-user-content.pdf", true)]
    [InlineData("synthetic-two-key-owner-content.pdf", false)]
    public void OwnerStripBindsParsingToTheUserKey(string name, bool expectedText)
    {
        string path = Path.Combine(AppContext.BaseDirectory, "Fixtures", "Statements", name);
        byte[] bytes = File.ReadAllBytes(path);
        using (PdfDocument original = PdfDocument.Open(bytes))
        {
            Assert.True(PdfEmptyUserAccess.Verify(original));
        }

        byte[]? stripped = PdfEmptyUserAccess.StripOwnerAuthentication(bytes);
        Assert.NotNull(stripped);
        bool sawText = false;
        try
        {
            using PdfDocument document = PdfDocument.Open(stripped!);
            string text = string.Join(" ", document.GetPage(1).GetWords().Select(word => word.Text));
            sawText = text.Contains("Synthetic", StringComparison.Ordinal);
        }
        catch (Exception)
        {
            sawText = false;
        }

        Assert.Equal(expectedText, sawText);
    }

    // Opt-in private evidence. CI does not set the folder, so the test returns
    // without reading any file. It never prints a path, value or document text.
    [Fact]
    public void PrivateApprovedSamplesVerifyWhenProvided()
    {
        string? folder = Environment.GetEnvironmentVariable("ARGUS_PRIVATE_PDF_DIR");
        if (string.IsNullOrWhiteSpace(folder) || !Directory.Exists(folder))
        {
            return;
        }

        string[] files = Directory.GetFiles(folder, "*.pdf");
        Assert.Equal(2, files.Length);
        foreach (string file in files)
        {
            using PdfDocument document = PdfDocument.Open(File.ReadAllBytes(file));
            Assert.True(document.IsEncrypted);
            Assert.True(PdfEmptyUserAccess.Verify(document));
        }
    }
}
